"""Build/check the self-contained SOCKS helpers in both published installers.

Run from any directory: python scripts/sync_socks_helpers.py [--check]
Only this generator should change the marked installer block.
"""
from __future__ import annotations

import argparse
import base64
import gzip
import hashlib
import io
from pathlib import Path
import sys
import textwrap


ROOT = Path(__file__).resolve().parents[1]
START = "# BEGIN GENERATED SOCKS HELPERS\n"
END = "# END GENERATED SOCKS HELPERS\n"
HELPERS = (
    ("socks_exit.sh", "SOCKS_EXIT_SHA256"),
    ("socks_node_probe.py", "SOCKS_EXIT_PROBE_SHA256"),
    ("socks_exit_job.py", "SOCKS_EXIT_JOB_SHA256"),
    ("proxy_input.py", "PROXY_INPUT_SHA256"),
    ("node_overview.py", "NODE_OVERVIEW_SHA256"),
    ("panel_release.py", "PANEL_RELEASE_SHA256"),
    ("panel_upgrade.py", "PANEL_UPGRADE_SHA256"),
)
ENTRYPOINTS = ("install.sh", "install_3xui_xhttp_vlessenc.sh")


def compressed(data: bytes) -> str:
    """Keep output identical across Python versions and host operating systems."""
    buffer = io.BytesIO()
    with gzip.GzipFile(fileobj=buffer, mode="wb", filename="", mtime=0) as archive:
        archive.write(data)
    return base64.b64encode(buffer.getvalue()).decode("ascii")


def generated_block(root: Path) -> str:
    data = [(name, variable, (root / "lib" / name).read_bytes())
            for name, variable in HELPERS]
    lines = [START.rstrip(), "# Generated by scripts/sync_socks_helpers.py; do not edit by hand."]
    for _, variable, content in data:
        lines.append(f'{variable}="{hashlib.sha256(content).hexdigest()}"')
    lines.extend(("socks_exit_embedded_helper() {", '    case "$1" in'))
    for index, (name, _, content) in enumerate(data):
        delimiter = f"SOCKS_HELPER_PAYLOAD_{index}"
        lines.append(f"        {name}) cat <<'{delimiter}'")
        lines.extend(textwrap.wrap(compressed(content), width=96))
        lines.extend((delimiter, "            ;;"))
    lines.extend(('        *) return 1 ;;', "    esac", "}", END.rstrip(), ""))
    return "\n".join(lines)


def render(source: str, root: Path) -> str:
    if source.count(START) != 1 or source.count(END) != 1:
        raise ValueError("installer must contain exactly one SOCKS helper block")
    before, rest = source.split(START, 1)
    _, after = rest.split(END, 1)
    return before + generated_block(root) + after


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if either installer needs regeneration")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        source = (args.root / ENTRYPOINTS[0]).read_text(encoding="utf-8")
        rendered = render(source, args.root).encode("utf-8")
        stale = [name for name in ENTRYPOINTS if (args.root / name).read_bytes() != rendered]
        if args.check:
            if stale:
                print("SOCKS helper bundle is stale: " + ", ".join(stale)
                      + "; run python scripts/sync_socks_helpers.py", file=sys.stderr)
                return 1
        else:
            for name in ENTRYPOINTS:
                (args.root / name).write_bytes(rendered)
        print("SOCKS helper bundle verified." if args.check else "SOCKS helper bundle synchronized.")
        return 0
    except (OSError, ValueError) as exc:
        print(f"Could not build SOCKS helper bundle: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
